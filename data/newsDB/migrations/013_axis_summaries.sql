-- 002: таблица axis_summaries — осевые саммари первого этапа.
--
-- Зачем. Двухэтапная суммаризация сначала делает девять осевых саммари, потом
-- сводит их в мету. До этой миграции в базу уходила только мета, а осевые
-- тексты — девять вызовов модели на дату — выбрасывались. Это и потеря
-- провенанса (из чего собрана мета, не видно), и потеря материала: сравнить,
-- что модель писала про `дкп` в разные периоды, было не по чему.
--
-- Ключ (run_date, axis): на дату по одной строке на ось, как в `summaries`
-- одна строка на дату. Горизонт и модель дублируются здесь намеренно —
-- строка должна быть интерпретируема без джойна, ровно по тем же соображениям,
-- по каким horizon_days лежит в `summaries`.
--
-- Отказавшие оси сюда не пишутся: вместо текста `amnesiac` подставляет
-- заглушку «(нет данных по оси из-за ошибки провайдера)», и хранить её как
-- саммари значит смешивать отсутствие данных с данными. Какие оси отвалились,
-- записано в summaries.failed_axes (миграция 001).
--
-- Применение:
--   sqlite3 data/newsDB/project.db < data/newsDB/migrations/013_axis_summaries.sql

CREATE TABLE axis_summaries (
    run_date      TEXT NOT NULL,
    axis          TEXT NOT NULL,
    horizon_days  INTEGER NOT NULL CHECK (horizon_days > 0),
    model         TEXT,
    summary       TEXT NOT NULL,
    doc_count     INTEGER,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (run_date, axis)
);
