-- 001: колонка failed_axes в таблице summaries.
--
-- Зачем. Саммари в режиме two_stage собирается из девяти осевых саммари, и при
-- max_failed_axes > 0 оно считается успешным, даже если часть осей отвалилась.
-- До этой миграции в summaries лежал только текст: дата с восемью осями из
-- девяти была неотличима от полной, и при чтении из кеша деградация исчезала
-- бесследно. Реальный случай: 2026-02-26, ось `курс` — провайдер вернул пустой
-- ответ, саммари ушло в кеш как обычное.
--
-- Формат. JSON-массив имён осей, ensure_ascii=False: '["курс"]'.
--   NULL — статус неизвестен: строка записана до этой миграции.
--   '[]'  — проверено, не отвалилось ничего.
-- Различие существенное: тринадцать унаследованных от blind_prophet строк
-- честно неизвестны, и приравнивать их к «всё в порядке» нельзя.
--
-- Применение (идемпотентности в ALTER TABLE нет, повторный запуск упадёт на
-- duplicate column name — это нормально):
--   sqlite3 data/newsDB/project.db < data/newsDB/migrations/012_summaries_failed_axes.sql

ALTER TABLE summaries ADD COLUMN failed_axes TEXT;
